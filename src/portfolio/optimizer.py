    # Internal — correlation / covariance helpers
    # ==================================================================

    @staticmethod
    def _default_correlation_matrix(
        n: int,
    ) -> list[list[float]]:
        """Build a default correlation matrix with uniform pairwise correlation.

        Uses ``_DEFAULT_CORRELATION`` (0.15) for off-diagonal entries
        and 1.0 on the diagonal.

        Args:
            n: Size of the matrix.

        Returns:
            NxN correlation matrix as a list of lists.
        """
        matrix: list[list[float]] = []
        for i in range(n):
            row: list[float] = []
            for j in range(n):
                row.append(1.0 if i == j else _DEFAULT_CORRELATION)
            matrix.append(row)
        return matrix

    @staticmethod
    def _build_covariance_matrix(
        risks: list[float],
        correlation_matrix: list[list[float]] | None,
    ) -> Any:
        """Build a covariance matrix from risks and correlation.

        Uses numpy when available for efficient construction.

        Args:
            risks: List of standard deviations.
            correlation_matrix: Optional NxN correlation matrix.

        Returns:
            Covariance matrix as a numpy array (if available) or
            list of lists.
        """
        n = len(risks)
        corr = correlation_matrix or PortfolioOptimizer._default_correlation_matrix(
            n
        )

        if _HAS_NUMPY:
            corr_arr = np.array(corr, dtype=float)
            std_arr = np.array(risks, dtype=float)
            return np.outer(std_arr, std_arr) * corr_arr

        # Fallback: pure Python
        cov: list[list[float]] = []
        for i in range(n):
            row: list[float] = []
            for j in range(n):
                c = corr[i][j] if i < len(corr) and j < len(
                    corr[i]
                ) else _DEFAULT_CORRELATION
                row.append(risks[i] * risks[j] * c)
            cov.append(row)
        return cov

