    @staticmethod
    def extract_from_trade_recommendation(
        recommendation: Any,
    ) -> dict[str, Any]:
        """Convert a ``TradeRecommendation`` to a standard dict.

        Works with :class:`~src.recommendations.engine.TradeRecommendation`
        or any object that has ``symbol``, ``signal``, ``confidence``,
        ``average_score``, ``entry_price`` attributes.

        Args:
            recommendation: A TradeRecommendation or compatible object.

        Returns:
            Dict with keys: ``symbol``, ``confidence``, ``score``,
            ``expected_return``, ``risk``, ``sector``, ``signal``,
            ``price``.
        """
        return {
            "symbol": getattr(recommendation, "symbol", ""),
            "signal": getattr(recommendation, "signal", "HOLD"),
            "confidence": float(
                getattr(recommendation, "confidence", 0.0)
            ),
            "score": float(
                getattr(recommendation, "average_score", 0.0)
            ),
            "expected_return": float(
                getattr(recommendation, "expected_return", 0.0)
            ),
            "risk": float(getattr(recommendation, "risk", 0.0)),
            "sector": str(
                getattr(recommendation, "sector", "Others")
            ),
            "price": (
                float(getattr(recommendation, "entry_price", 0.0))
                if getattr(recommendation, "entry_price", None)
                is not None
                else 0.0
            ),
        }

    # ==================================================================
    # Internal — recommendation filtering
    # ==================================================================

    def _filter_recommendations(
        self,
        recommendations: list[dict[str, Any]],
        max_positions: int,
        min_confidence: float,
        min_score: float,
    ) -> list[dict[str, Any]]:
        """Filter and sort recommendations.

        Keeps only BUY signals, enforces minimum confidence and score
        thresholds, caps the number of positions, and sorts by score
        descending.

        Args:
            recommendations: Raw recommendation list.
            max_positions: Maximum number of positions.
            min_confidence: Minimum confidence (0–100).
            min_score: Minimum score.

        Returns:
            Filtered and sorted recommendation list.
        """
        # Parse recommendations from possible TradeRecommendation objs
        parsed: list[dict[str, Any]] = []
        for rec in recommendations:
            if isinstance(rec, dict):
                parsed.append(rec)
            else:
                parsed.append(
                    self.extract_from_trade_recommendation(rec)
                )

        # Filter: only BUY signals with valid symbols
        filtered = [
            r
            for r in parsed
            if r.get("signal", "HOLD").upper().strip() == "BUY"
            and r.get("symbol")
        ]

        # Apply confidence threshold
        if min_confidence > 0:
            filtered = [
                r
                for r in filtered
                if float(r.get("confidence", 0.0)) >= min_confidence
            ]

        # Apply score threshold
        if min_score > 0:
            filtered = [
                r
                for r in filtered
                if float(r.get("score", 0.0)) >= min_score
            ]

        # Sort by score descending
        filtered.sort(
            key=lambda r: float(r.get("score", 0.0)),
            reverse=True,
        )

        # Cap positions
        if max_positions > 0:
            filtered = filtered[:max_positions]

        return filtered

    # ==================================================================
    # Internal — validation
    # ==================================================================

    @staticmethod
    def _validate_correlation_matrix(
        correlation_matrix: list[list[float]] | None,
        expected_size: int,
    ) -> None:
        """Validate an optional correlation matrix.

        Args:
            correlation_matrix: The matrix to validate, or None.
            expected_size: Expected number of rows/cols.

        Raises:
            ValueError: If the matrix is invalid.
        """
        if correlation_matrix is None:
            return

        if not isinstance(correlation_matrix, list):
            raise ValueError(
                "correlation_matrix must be a list of lists."
            )

        n = len(correlation_matrix)
        if n != expected_size:
            raise ValueError(
                f"correlation_matrix size ({n}) does not match "
                f"number of recommendations ({expected_size})."
            )

        for i, row in enumerate(correlation_matrix):
            if not isinstance(row, list):
                raise ValueError(
                    f"Row {i} of correlation_matrix is not a list."
                )
            if len(row) != expected_size:
                raise ValueError(
                    f"Row {i} of correlation_matrix has length "
                    f"{len(row)}, expected {expected_size}."
                )
            for j, val in enumerate(row):
                if not isinstance(val, (int, float)):
                    raise ValueError(
                        f"correlation_matrix[{i}][{j}] is not a "
                        f"number, got {type(val).__name__}."
                    )
                if val < -1.0 or val > 1.0:
                    raise ValueError(
                        f"correlation_matrix[{i}][{j}] = {val} "
                        f"is outside [-1, 1]."
                    )

