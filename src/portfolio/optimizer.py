"""Portfolio Optimisation Engine for the NEPSE Quant Engine.

Constructs optimal portfolios from BUY recommendations generated by
the :class:`~src.recommendations.engine.RecommendationEngine`.

Integrates with:

- :class:`~src.recommendations.engine.RecommendationEngine`
- :class:`~src.risk.engine.RiskEngine`
- :class:`~src.portfolio.allocator.PortfolioAllocator`
- :class:`~src.simulation.monte_carlo.MonteCarloSimulator`
- :class:`~src.analytics.performance.PerformanceAnalyzer`
- :class:`~src.optimization.walk_forward.WalkForwardOptimizer`
- :class:`~src.optimization.parameter_optimizer.ParameterOptimizer`

without modifying any of their public APIs.

Supports six optimisation methods:

1. **Equal Weight** — distribute capital equally among all positions.
2. **Maximum Sharpe** — maximise the risk-adjusted return.
3. **Minimum Variance** — minimise portfolio volatility.
4. **Risk Parity** — equal risk contribution from each position.
5. **Score Weighted** — weights proportional to recommendation score.
6. **Confidence Weighted** — weights proportional to confidence.

Designed for future extensibility with Black-Litterman, Hierarchical
Risk Parity, Mean-CVaR, Equal Risk Contribution, and Kelly portfolio
optimisation methods.
"""

