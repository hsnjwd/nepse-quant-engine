    # ==================================================================
    # Summary
    # ==================================================================

    def summary(
        self,
        result: PortfolioOptimizationResult,
    ) -> dict[str, Any]:
        """Return a concise summary of an optimisation result.

        Args:
            result: A :class:`PortfolioOptimizationResult` instance.

        Returns:
            Dictionary with key portfolio metrics.
        """
        num_positions = len(result.allocations)
        capital_used = result.capital_used
        cash_remaining = self._capital - capital_used

        weights = [a.weight for a in result.allocations]
        avg_position = (
            (capital_used / num_positions) if num_positions else 0.0
        )
        largest_position = max(weights) if weights else 0.0
        smallest_position = min(weights) if weights else 0.0

        return {
            "method": result.method,
            "expected_return": round(result.expected_return, 4),
            "portfolio_volatility": round(result.portfolio_risk, 4),
            "sharpe_ratio": round(result.sharpe_ratio, 4),
            "diversification_score": round(
                result.diversification_score, 4
            ),
            "positions": num_positions,
            "capital_used": round(capital_used, 2),
            "cash_remaining": round(cash_remaining, 2),
            "average_position_size": round(avg_position, 2),
            "largest_position_weight": round(largest_position, 4),
            "smallest_position_weight": round(smallest_position, 4),
            "largest_holding": (
                max(
                    result.allocations,
                    key=lambda a: a.weight,
                ).symbol
                if result.allocations
                else None
            ),
            "sector_allocation": {
                k: round(v, 4)
                for k, v in result.sector_exposure.items()
            },
        }

    # ==================================================================
    # Internal — unified optimisation dispatcher
    # ==================================================================

    def _optimize(
        self,
        method: str,
        recommendations: list[dict[str, Any]],
        correlation_matrix: list[list[float]] | None = None,
        max_positions: int = _MAX_POSITIONS_DEFAULT,
        min_confidence: float = _MIN_CONFIDENCE_DEFAULT,
        min_score: float = _MIN_SCORE_DEFAULT,
    ) -> PortfolioOptimizationResult:
        """Unified optimisation dispatcher.

        Validates inputs, filters recommendations, dispatches to the
        appropriate method, builds allocations, computes portfolio
        metrics, and returns the result.

        Args:
            method: Optimisation method name.
            recommendations: List of recommendation dicts.
            correlation_matrix: Optional correlation matrix.
            max_positions: Max positions to include.
            min_confidence: Min confidence threshold.
            min_score: Min score threshold.

        Returns:
            PortfolioOptimizationResult with the optimised portfolio.

        Raises:
            ValueError: For invalid inputs or empty filtered list.
        """
        # ---- Validate method ----
        if method not in _VALID_METHODS:
            raise ValueError(
                f"Unknown optimisation method '{method}'. "
                f"Valid methods: {sorted(_VALID_METHODS)}"
            )

        # ---- Validate recommendations ----
        if not recommendations:
            raise ValueError(
                "Cannot optimise an empty recommendation list."
            )

        if not isinstance(recommendations, list):
            raise ValueError(
                "recommendations must be a list, "
                f"got {type(recommendations).__name__}."
            )

        logger.info(
            "Optimisation started: method=%s, recommendations=%d",
            method,
            len(recommendations),
        )

        # ---- Filter recommendations ----
        filtered = self._filter_recommendations(
            recommendations=recommendations,
            max_positions=max_positions,
            min_confidence=min_confidence,
            min_score=min_score,
        )

        if not filtered:
            raise ValueError(
                "No recommendations pass the filtering criteria "
                f"(max_positions={max_positions}, "
                f"min_confidence={min_confidence}, "
                f"min_score={min_score})."
            )

        logger.info(
            "Method=%s: %d recommendations after filtering.",
            method,
            len(filtered),
        )

        # ---- Validate correlation matrix ----
        self._validate_correlation_matrix(
            correlation_matrix, len(filtered)
        )

        # ---- Extract arrays ----
        symbols = [r["symbol"] for r in filtered]
        expected_returns = [
            float(r.get("expected_return", 0.0)) for r in filtered
        ]
        risks = [float(r.get("risk", 0.0)) for r in filtered]
        sectors = [str(r.get("sector", "Others")) for r in filtered]
        scores = [float(r.get("score", 0.0)) for r in filtered]
        confidences = [
            float(r.get("confidence", 0.0)) for r in filtered
        ]

        # ---- Compute raw weights by method ----
        raw_weights = self._compute_weights(
            method=method,
            expected_returns=expected_returns,
            risks=risks,
            scores=scores,
            confidences=confidences,
            correlation_matrix=correlation_matrix,
        )

        # ---- Apply constraints ----
        constrained_weights = self._apply_constraints(
            weights=raw_weights,
            sectors=sectors,
        )

        # ---- Rebuild final weights after constraint enforcement ----
        # Only re-normalise when constrained weights exceed 100 %.
        # When max_position_weight limits push total below 1.0 the
        # remainder stays as cash rather than being re-leveraged.
        cw_sum = sum(constrained_weights)
        if cw_sum > 1.0:
            final_weights = [w / cw_sum for w in constrained_weights]
        else:
            final_weights = constrained_weights

        # ---- Check sector limits ----
        violations = self._check_sector_limits(
            weights=final_weights,
            sectors=sectors,
            symbols=symbols,
        )

        # ---- Build allocations ----
        prices = [
            float(r.get("price", 0.0)) for r in filtered
        ]
        allocations = self._build_allocations(
            symbols=symbols,
            weights=final_weights,
            expected_returns=expected_returns,
            risks=risks,
            sectors=sectors,
            prices=prices,
        )

        # ---- Compute portfolio metrics ----
        portfolio_return = self._portfolio_return(
            final_weights, expected_returns
        )
        portfolio_variance = self._portfolio_variance(
            weights=final_weights,
            risks=risks,
            correlation_matrix=correlation_matrix,
        )
        portfolio_vol = math.sqrt(portfolio_variance)
        sharpe = self._sharpe_ratio(portfolio_return, portfolio_vol)
        div_score = self._diversification_score(
            weights=final_weights,
            risks=risks,
            portfolio_variance=portfolio_variance,
        )

        # ---- Sector exposure from actual allocated weights ----
        sector_exposure = self._compute_sector_exposure_from_allocations(
            allocations,
        )

        capital_used = sum(a.capital for a in allocations)
        cash_remaining = self._capital - capital_used

        # ---- Build result ----
        result = PortfolioOptimizationResult(
            method=method,
            expected_return=portfolio_return,
            portfolio_risk=portfolio_vol,
            sharpe_ratio=sharpe,
            diversification_score=div_score,
            capital_used=round(capital_used, 2),
            cash_remaining=round(cash_remaining, 2),
            allocations=allocations,
            weights={
                a.symbol: a.weight for a in allocations
            },
            sector_exposure=sector_exposure,
            summary=(
                f"Optimised {len(allocations)} positions using "
                f"'{method}' method — Sharpe: {sharpe:.4f}, "
                f"Risk: {portfolio_vol:.4f}, "
                f"Return: {portfolio_return:.4f}, "
                f"Capital used: NPR {capital_used:,.2f}"
            ),
            constraint_violations=violations,
        )

        # ---- Log completion ----
        logger.info(
            "Optimisation complete: method=%s, positions=%d, "
            "sharpe=%.4f, risk=%.4f, return=%.4f, "
            "capital_used=%.2f, cash_remaining=%.2f",
            method,
            len(allocations),
            sharpe,
            portfolio_vol,
            portfolio_return,
            capital_used,
            cash_remaining,
        )

        return result

    # ==================================================================
    # Internal — weight computation
    # ==================================================================

    def _compute_weights(
        self,
        method: str,
        expected_returns: list[float],
        risks: list[float],
        scores: list[float],
        confidences: list[float],
        correlation_matrix: list[list[float]] | None,
    ) -> list[float]:
        """Dispatch to the appropriate weight-computation method.

        Args:
            method: Optimisation method name.
            expected_returns: List of expected returns.
            risks: List of position risks (standard deviations).
            scores: List of recommendation scores.
            confidences: List of confidence values.
            correlation_matrix: Optional correlation matrix.

        Returns:
            List of raw weights (may sum to 1 or less).
        """
        n = len(expected_returns)

        if method == "equal_weight":
            return self._weights_equal_weight(n)

        elif method == "max_sharpe":
            if _HAS_SCIPY and _HAS_NUMPY:
                return self._weights_max_sharpe_scipy(
                    expected_returns, risks, correlation_matrix
                )
            logger.warning(
                "scipy/numpy not available — falling back to "
                "equal-weight for max_sharpe."
            )
            return self._weights_equal_weight(n)

        elif method == "min_variance":
            if _HAS_SCIPY and _HAS_NUMPY:
                return self._weights_min_variance_scipy(
                    risks, correlation_matrix
                )
            logger.warning(
                "scipy/numpy not available — falling back to "
                "equal-weight for min_variance."
            )
            return self._weights_equal_weight(n)

        elif method == "risk_parity":
            return self._weights_risk_parity(
                risks, correlation_matrix
            )

        elif method == "score_weighted":
            return self._weights_proportional(scores)

        elif method == "confidence_weighted":
            return self._weights_proportional(confidences)

        return self._weights_equal_weight(n)

    # ==================================================================
    # Internal — individual weight methods
    # ==================================================================

    @staticmethod
    def _weights_equal_weight(n: int) -> list[float]:
        """Compute equal weights for N positions.

        Args:
            n: Number of positions.

        Returns:
            List of equal weights summing to 1.
        """
        if n <= 0:
            return []
        weight = 1.0 / n
        return [weight] * n

    @staticmethod
    def _weights_proportional(values: list[float]) -> list[float]:
        """Compute weights proportional to a list of positive values.

        Args:
            values: List of numeric values (e.g. scores, confidences).

        Returns:
            Normalised weights summing to 1. Falls back to equal
            weights if all values are zero.
        """
        if not values:
            return []
        total = sum(max(v, 0.0) for v in values)
        if total <= 0:
            n = len(values)
            return [1.0 / n] * n
        return [max(v, 0.0) / total for v in values]

    def _weights_max_sharpe_scipy(
        self,
        expected_returns: list[float],
        risks: list[float],
        correlation_matrix: list[list[float]] | None,
    ) -> list[float]:
        """Maximise Sharpe ratio using scipy SLSQP.

        Args:
            expected_returns: List of expected returns.
            risks: List of standard deviations.
            correlation_matrix: Optional correlation matrix.

        Returns:
            Optimised weight vector.
        """
        n = len(expected_returns)
        cov_matrix = self._build_covariance_matrix(
            risks, correlation_matrix
        )

        # Objective: minimise negative Sharpe
        def _neg_sharpe(w: np.ndarray) -> float:  # type: ignore[no-untyped-def]
            ret = float(np.dot(w, expected_returns))
            var = float(w.T @ cov_matrix @ w)
            vol = math.sqrt(max(var, 1e-16))
            if vol == 0:
                return 0.0
            sharpe = (ret - self._risk_free_rate) / vol
            return -sharpe  # negate for minimisation

        return self._run_scipy_optimize(n, _neg_sharpe)

    def _weights_min_variance_scipy(
        self,
        risks: list[float],
        correlation_matrix: list[list[float]] | None,
    ) -> list[float]:
        """Minimise portfolio variance using scipy SLSQP.

        Args:
            risks: List of standard deviations.
            correlation_matrix: Optional correlation matrix.

        Returns:
            Optimised weight vector.
        """
        n = len(risks)
        cov_matrix = self._build_covariance_matrix(
            risks, correlation_matrix
        )

        def _variance(w: np.ndarray) -> float:  # type: ignore[no-untyped-def]
            return float(w.T @ cov_matrix @ w)

        return self._run_scipy_optimize(n, _variance)

    def _run_scipy_optimize(
        self,
        n: int,
        objective: Any,
    ) -> list[float]:
        """Run a scipy SLSQP optimisation with equality and bound constraints.

        Args:
            n: Number of assets.
            objective: Objective function to minimise.

        Returns:
            Optimised weight vector (list of floats).
        """
        # Initial guess: equal weight
        x0 = np.array([1.0 / n] * n, dtype=float)

        # Bounds: use (0, 1) here — let _apply_constraints handle
        # the min/max weight clamping after optimisation so that the
        # equality constraint (sum = 1) remains feasible.
        bounds = [(0.0, 1.0) for _ in range(n)]

        # Constraint: sum of weights = 1
        constraints = [
            {
                "type": "eq",
                "fun": lambda w: np.sum(w) - 1.0,
            }
        ]

        result = _scipy_minimize(
            objective,
            x0,
            method="SLSQP",
            bounds=bounds,
            constraints=constraints,
            tol=_SCIPY_TOL,
            options={"maxiter": _SCIPY_MAXITER},
        )

        if not result.success:
            logger.warning(
                "scipy optimisation did not converge: %s. "
                "Falling back to equal weight.",
                result.message,
            )
            return [1.0 / n] * n

        return result.x.tolist()

    def _weights_risk_parity(
        self,
        risks: list[float],
        correlation_matrix: list[list[float]] | None,
    ) -> list[float]:
        """Compute risk-parity weights using an iterative algorithm.

        Uses the coordinate-descent approach to equalise risk
        contributions from each position.

        Args:
            risks: List of standard deviations.
            correlation_matrix: Optional correlation matrix.

        Returns:
            Risk-parity weight vector.
        """
        n = len(risks)
        if n <= 1:
            return [1.0] if n == 1 else []

        # Use scipy if available for a more accurate solution
        if _HAS_SCIPY and _HAS_NUMPY:
            cov_matrix = self._build_covariance_matrix(
                risks, correlation_matrix
            )

            def _risk_parity_objective(w: np.ndarray) -> float:  # type: ignore[no-untyped-def]
                portfolio_var = float(w.T @ cov_matrix @ w)
                if portfolio_var <= 0:
                    return 0.0
                # Marginal risk contributions
                mrc = (cov_matrix @ w).tolist()
                # Risk contributions
                rc = [float(w[i] * mrc[i]) for i in range(n)]
                # Objective: sum of squared differences between RC pairs
                objective = 0.0
                for i in range(n):
                    for j in range(i + 1, n):
                        objective += (rc[i] - rc[j]) ** 2
                return objective

            return self._run_scipy_optimize(n, _risk_parity_objective)

        # Fallback: iterative coordinate descent (no scipy)
        weights = [1.0 / n] * n
        corr = correlation_matrix or self._default_correlation_matrix(
            n
        )
        max_iter = 100
        tol = 1e-6

        for _ in range(max_iter):
            # Compute marginal risk contributions
            portfolio_var = self._portfolio_variance(
                weights, risks, corr
            )
            if portfolio_var <= 0:
                break

            mrc = self._marginal_risk_contributions(
                weights, risks, corr
            )
            rc = [weights[i] * mrc[i] for i in range(n)]
            avg_rc = sum(rc) / n

            # Adjust weights
            new_weights = [
                max(
                    self._min_weight,
                    min(
                        self._max_weight,
                        weights[i] * (avg_rc / max(rc[i], 1e-16)),
                    ),
                )
                for i in range(n)
            ]

            # Normalise
            total = sum(new_weights)
            if total > 0:
                new_weights = [w / total for w in new_weights]

            # Check convergence
            diff = sum(
                abs(new_weights[i] - weights[i]) for i in range(n)
            )
            weights = new_weights
            if diff < tol:
                break

        return weights

    # ==================================================================
    # Internal — constraint enforcement
    # ==================================================================

    def _apply_constraints(
        self,
        weights: list[float],
        sectors: list[str],
    ) -> list[float]:
        """Apply position weight and sector constraints.

        Enforces min/max per-position weights and sector exposure
        limits iteratively.

        Sector weights are only reduced when the accumulated exposure
        for that sector would exceed the configured limit; otherwise
        the original weights are preserved exactly.

        All sector weight arithmetic uses ``round(..., 10)`` to
        prevent floating-point drift (e.g. ``0.30000000000000004``).

        Args:
            weights: Raw weight vector.
            sectors: Sector labels for each position.

        Returns:
            Constrained weight vector.
        """
        n = len(weights)
        constrained = list(weights)

        # 1. Clamp individual weights to [min_weight, max_weight]
        for i in range(n):
            constrained[i] = max(
                self._min_weight,
                min(self._max_weight, constrained[i]),
            )

        # 2. Enforce sector limits — only clamp when the limit would
        #    actually be exceeded.  Otherwise preserve the ideal weight.
        sector_weight: dict[str, float] = {}
        for i, sector in enumerate(sectors):
            cur = sector_weight.get(sector, 0.0)
            if cur + constrained[i] > self._sector_limit:
                # Cap this position so the sector fills exactly to the limit
                constrained[i] = max(
                    0.0,
                    round(self._sector_limit - cur, 10),
                )
            # Always track the running sector total with rounding
            sector_weight[sector] = round(
                sector_weight.get(sector, 0.0) + constrained[i],
                10,
            )

        # 3. Normalise to sum to 1 only when weights exceed 100%
        # (clamping can push individual weights down, and we want to
        #  leave cash on the side rather than re-leveraging).
        total = sum(constrained)
        if total > 1.0:
            constrained = [w / total for w in constrained]

        return constrained

    def _check_sector_limits(
        self,
        weights: list[float],
        sectors: list[str],
        symbols: list[str],
    ) -> list[str]:
        """Check whether any sector exceeds the configured limit.

        Args:
            weights: Final weight vector.
            sectors: Sector labels for each position.
            symbols: Symbol names for reporting.

        Returns:
            List of violation messages (empty if none).
        """
        violations: list[str] = []
        sector_exposure: dict[str, float] = {}
        for i, sector in enumerate(sectors):
            sector_exposure[sector] = (
                sector_exposure.get(sector, 0.0) + weights[i]
            )

        for sector, exposure in sector_exposure.items():
            if exposure > self._sector_limit:
                violations.append(
                    f"Sector '{sector}' exposure {exposure:.4f} "
                    f"exceeds limit {self._sector_limit:.4f}."
                )

        return violations

    # ==================================================================
    # Internal — allocation building
    # ==================================================================

    def _build_allocations(
        self,
        symbols: list[str],
        weights: list[float],
        expected_returns: list[float],
        risks: list[float],
        sectors: list[str],
        prices: list[float] | None = None,
    ) -> list[PortfolioAllocation]:
        """Build PortfolioAllocation objects from weights and metadata.

        Share counts are computed from the position capital divided by
        the actual price per share.  When price data is unavailable (0
        or missing), shares default to the integer floor of the capital
        amount.

        Args:
            symbols: List of ticker symbols.
            weights: List of portfolio weights.
            expected_returns: List of expected returns.
            risks: List of position risks.
            sectors: List of sector labels.
            prices: Optional list of per-share prices for share
                calculation.  Missing or zero prices are substituted
                with 1.0 so that capital ≈ shares.

        Returns:
            List of :class:`PortfolioAllocation` instances.
        """
        allocations: list[PortfolioAllocation] = []
        prices = prices or []
        for i, symbol in enumerate(symbols):
            # Defensive clamp: enforce min/max position weight even if the
            # upstream constraint pipeline was bypassed or failed.
            raw_weight = weights[i]
            weight = max(
                self._min_weight,
                min(self._max_weight, raw_weight),
            )
            capital = self._capital * weight
            price = prices[i] if i < len(prices) and prices[i] > 0 else 1.0
            shares = int(capital / max(price, 1.0))
            actual_capital = shares * price

            allocations.append(
                PortfolioAllocation(
                    symbol=symbol,
                    weight=weight,
                    shares=shares,
                    capital=round(actual_capital, 2),
                    expected_return=expected_returns[i],
                    risk=risks[i],
                    sector=sectors[i],
                )
            )

        return allocations

    # ==================================================================
    # Internal — portfolio metrics
    # ==================================================================

    @staticmethod
    def _portfolio_return(
        weights: list[float],
        expected_returns: list[float],
    ) -> float:
        """Compute the weighted portfolio return.

        Args:
            weights: Portfolio weights.
            expected_returns: Per-position expected returns.

        Returns:
            Weighted average return.
        """
        if not weights or not expected_returns:
            return 0.0
        return sum(
            w * r for w, r in zip(weights, expected_returns)
        )

    def _portfolio_variance(
        self,
        weights: list[float],
        risks: list[float],
        correlation_matrix: list[list[float]] | None,
    ) -> float:
        """Compute the portfolio variance.

        If a correlation matrix is provided, uses it.  Otherwise falls
        back to an independent-asset assumption with a default pairwise
        correlation.

        Args:
            weights: Portfolio weights.
            risks: Per-position standard deviations.
            correlation_matrix: Optional NxN correlation matrix.

        Returns:
            Portfolio variance.
        """
        n = len(weights)
        if n == 0:
            return 0.0

        if n == 1:
            return risks[0] ** 2 if risks else 0.0

        corr = correlation_matrix or self._default_correlation_matrix(
            n
        )

        var = 0.0
        for i in range(n):
            for j in range(n):
                ci = corr[i][j] if i < len(corr) and j < len(
                    corr[i]
                ) else _DEFAULT_CORRELATION
                var += (
                    weights[i]
                    * weights[j]
                    * risks[i]
                    * risks[j]
                    * ci
                )

        return var

    def _marginal_risk_contributions(
        self,
        weights: list[float],
        risks: list[float],
        correlation_matrix: list[list[float]],
    ) -> list[float]:
        """Compute marginal risk contributions for each position.

        MRC_i = (cov_matrix @ weights)_i / portfolio_vol

        Args:
            weights: Portfolio weights.
            risks: Per-position standard deviations.
            correlation_matrix: NxN correlation matrix.

        Returns:
            List of marginal risk contributions.
        """
        n = len(weights)
        port_var = self._portfolio_variance(
            weights, risks, correlation_matrix
        )
        port_vol = math.sqrt(max(port_var, 1e-16))

        mrc: list[float] = []
        for i in range(n):
            cov_sum = 0.0
            for j in range(n):
                ci = correlation_matrix[i][j] if i < len(
                    correlation_matrix
                ) and j < len(correlation_matrix[i]) else _DEFAULT_CORRELATION
                cov_sum += weights[j] * risks[i] * risks[j] * ci
            mrc.append(cov_sum / port_vol)

        return mrc

    def _sharpe_ratio(
        self,
        portfolio_return: float,
        portfolio_vol: float,
    ) -> float:
        """Compute the Sharpe ratio.

        Args:
            portfolio_return: Expected portfolio return.
            portfolio_vol: Portfolio volatility (standard deviation).

        Returns:
            Sharpe ratio, or ``0.0`` if volatility is zero.
        """
        if portfolio_vol <= 0:
            return 0.0
        if portfolio_return - self._risk_free_rate <= 0:
            return 0.0
        return (
            portfolio_return - self._risk_free_rate
        ) / portfolio_vol

    @staticmethod
    def _diversification_score(
        weights: list[float],
        risks: list[float],
        portfolio_variance: float,
    ) -> float:
        """Compute the diversification score.

        A portfolio with only one position is not diversified — the
        score is always ``0.0`` in that case.

        For multi-position portfolios the formula is:
            score = 1 - (sum(w_i^2 * sigma_i^2) / var_portfolio)

        A score of 0 = no diversification (single stock equivalent).
        A score approaching 1 = highly diversified.

        Args:
            weights: Portfolio weights.
            risks: Per-position standard deviations.
            portfolio_variance: Total portfolio variance.

        Returns:
            Diversification score in [0, 1].
        """
        # Single position → not diversified
        if len(weights) <= 1:
            return 0.0

        if portfolio_variance <= 0:
            return 0.0

        numerator = sum(
            (w ** 2) * (r ** 2)
            for w, r in zip(weights, risks)
        )

        if numerator <= 0:
            return 0.0

        score = 1.0 - (numerator / portfolio_variance)
        return max(0.0, min(1.0, score))

    @staticmethod
    def _compute_sector_exposure(
        weights: list[float],
        sectors: list[str],
    ) -> dict[str, float]:
        """Compute total exposure per sector.

        Args:
            weights: Portfolio weights.
            sectors: Sector labels for each position.

        Returns:
            Dictionary mapping sector names to total weight.
        """
        exposure: dict[str, float] = {}
        for w, sector in zip(weights, sectors):
            exposure[sector] = exposure.get(sector, 0.0) + w

        # Ensure all categories appear
        for category in _SECTOR_CATEGORIES:
            if category not in exposure:
                exposure[category] = 0.0

        return exposure

    @staticmethod
    def _compute_sector_exposure_from_allocations(
        allocations: list[PortfolioAllocation],
    ) -> dict[str, float]:
        """Compute sector exposure from the final allocation objects.

        Uses the actual ``.weight`` and ``.sector`` fields on each
        :class:`PortfolioAllocation`, which reflect any clamping that
        happened during allocation building.

        Args:
            allocations: List of final :class:`PortfolioAllocation`
                instances.

        Returns:
            Dictionary mapping sector names to total allocated weight.
        """
        exposure: dict[str, float] = {}
        for alloc in allocations:
            exposure[alloc.sector] = (
                exposure.get(alloc.sector, 0.0) + alloc.weight
            )
        # Ensure all categories appear
        for category in _SECTOR_CATEGORIES:
            if category not in exposure:
                exposure[category] = 0.0
        return exposure

