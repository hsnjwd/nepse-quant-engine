def store_names() -> list[str]:
    """Names of every registered store (deterministic order)."""
    return [store.name for store in STATE_STORES]


def store_by_name(name: str) -> StateStore | None:
    """Return the store with *name*, or ``None``."""
    for store in STATE_STORES:
        if store.name == name:
            return store
    return None


def json_stores() -> list[StateStore]:
    """Every registered JSON store (used by the corruption matrix tests)."""
    return [s for s in STATE_STORES if s.store_format == "json"]


