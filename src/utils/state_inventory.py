"""Persistent-state inventory (Sprint 13.9 §12).

A single source of truth describing every durable store the platform
writes, so operators and tooling can reason about location, format,
versioning, atomicity, locking, corruption behaviour, backup and
migration without reading every module.

This is **metadata only** — it creates no state store, writes no files,
and must never be treated as a store itself.  ``STATE_STORES`` is a
frozen, ordered tuple; tests assert it stays accurate (every JSON store
in the platform routes through ``src.utils.json_store``, every entry's
owner module imports, etc.).

The human-readable mirror lives in ``docs/STATE_INVENTORY.md``.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class StateStore:
    """One durable store and its operational contract."""

    name: str
    owner: str            # module that owns the store
    location: str         # path template; {NEPSE_HOME} expands at runtime
    store_format: str     # json | csv | sqlite | text
    versioned: bool       # in-file schema version tracked & enforced
    atomic_writes: bool   # temp-file + os.replace
    cross_process_lock: bool  # json_store cross-process lock
    corruption_policy: str    # what happens on a damaged file
    backup: str               # mechanism that backs this store up
    migration: str            # versioned migration / none required
    rollback: str             # how an operator rolls this store back
    bounded: bool             # growth is bounded


